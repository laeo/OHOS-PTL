#!/bin/bash
# update_image_id.sh <image.img> [TAG]
#
# Regenerate the in-image identity stamp so it ALWAYS describes the image it
# lives in.  The stamp used to be written once and never refreshed, so a
# device kept reporting the hashes of a 10-rounds-old image and we wrongly
# concluded "the device is not running our build" (see fix_perf2/FINDINGS.md).
#
# Writes into p2 (/system):
#   /system/etc/ohos-image-id            human readable summary
#   /system/etc/ohos-image-id.manifest   per-key-file sha256 list
#   /system/bin/zz_imageid.sh            recomputes everything on the device
#
# Algorithm of P2_KEYFILES_SHA256 must match zz_imageid.sh exactly:
#   for each key: sha256sum "/$k"   (symlinks are followed)
#   | sha256sum
set -euo pipefail

IMG="${1:?usage: update_image_id.sh <image.img> [TAG]}"
TAG="${2:-}"
[ -n "$TAG" ] || TAG="pc_ptl-$(date -u +%Y%m%d-%H%M%SZ)"

WORK="$(mktemp -d "${TMPDIR:-/home/katax/Public/OHOS/out/x86_64_virt/ohos-dbg}/.imgid.XXXXXX")"
trap 'rm -rf "$WORK"' EXIT

# GPT: p1=ESP p2=system p3=vendor p4=sys_prod p5=chip_prod
P1_START=2048;       P1_SECS=1048576
P2_START=1050624;    P2_SECS=4194304
P3_START=5244928;    P3_SECS=1048576
P4_START=6293504;    P4_SECS=131072
P5_START=6424576;    P5_SECS=131072

echo "== extracting partitions =="
dd if="$IMG" of="$WORK/p1" bs=512 skip=$P1_START count=$P1_SECS status=none
dd if="$IMG" of="$WORK/p2" bs=512 skip=$P2_START count=$P2_SECS status=none
dd if="$IMG" of="$WORK/p3" bs=512 skip=$P3_START count=$P3_SECS status=none
dd if="$IMG" of="$WORK/p4" bs=512 skip=$P4_START count=$P4_SECS status=none
dd if="$IMG" of="$WORK/p5" bs=512 skip=$P5_START count=$P5_SECS status=none

KEYS='system/bin/aplay
system/bin/amixer
system/bin/speaker-test
system/lib64/libasound.so
system/etc/audio/alsa/share/alsa.conf
system/etc/audio/alsa/share/smixer.conf
system/etc/audio/alsa/share/cards/HDA-Intel.conf
system/bin/zz_audiotest
system/bin/zz_audioup.sh
system/etc/init/zz_audio.cfg
system/bin/zz_btbring.sh
system/bin/zz_imageid.sh
system/bin/ohos-diag
system/bin/zz_diag_boot.sh
system/app/SceneBoard/SceneBoard.hap
system/app/Terminal/Terminal.hap
system/app/org.aira.browser/Aira.hap
system/app/com.ohos.rimeime/RimeIme.hap
system/app/com.ohos.settings/Settings.hap
system/bin/ohosshd
system/bin/sudo
system/lib64/platformsdk/librender_service_base.z.so
system/lib64/libcursor_drawing_adapter.z.so
system/lib64/librender_service.z.so
system/lib64/platformsdk/libmmi-util.z.so'

mkdir -p "$WORK/kf"
: > "$WORK/manifest"
i=0
while IFS= read -r k; do
    [ -z "$k" ] && continue
    i=$((i+1))
    st=$(debugfs -R "stat /$k" "$WORK/p2" 2>/dev/null || true)
    tgt=$(printf '%s\n' "$st" | grep -A1 'Fast link dest' | tail -1 | sed 's/.*: //' | tr -d '\r' || true)
    if [ -n "$tgt" ]; then
        case "$tgt" in /*) real="$tgt";; *) real="$(dirname "/$k")/$tgt";; esac
    else
        real="/$k"
    fi
    debugfs -R "dump $real $WORK/kf/f$i" "$WORK/p2" >/dev/null 2>&1 || true
    if [ -s "$WORK/kf/f$i" ]; then
        printf '%s  /%s\n' "$(sha256sum "$WORK/kf/f$i" | cut -d' ' -f1)" "$k" >> "$WORK/manifest"
    else
        printf 'MISSING  /%s\n' "$k" >> "$WORK/manifest"
    fi
done <<< "$KEYS"

P2KF=$(sha256sum "$WORK/manifest" | cut -d' ' -f1)
ESP=$(sha256sum "$WORK/p1" | cut -d' ' -f1)
VEND=$(sha256sum "$WORK/p3" | cut -d' ' -f1)
SYSP=$(sha256sum "$WORK/p4" | cut -d' ' -f1)
CHIP=$(sha256sum "$WORK/p5" | cut -d' ' -f1)
UTC=$(date -u +%Y-%m-%dT%H:%M:%SZ)

cat > "$WORK/id" <<EOF
# pc_ptl image identity stamp (regenerated by partdisk/update_image_id.sh)
# If this file's hashes do not match the partitions you are running, you are
# NOT running this image.  Recompute on device with /system/bin/zz_imageid.sh verify
IMAGE_TAG=$TAG
BUILT_FOR=pc_ptl x86_64 2in1 OpenHarmony-7.0 linux-7.2
INJECTED_UTC=$UTC
ESP_PART_SHA256=$ESP
VENDOR_PART_SHA256=$VEND
SYS_PROD_PART_SHA256=$SYSP
CHIP_PROD_PART_SHA256=$CHIP
P2_KEYFILES_SHA256=$P2KF
P2_KEYFILES_LIST=/system/etc/ohos-image-id.manifest
EOF

echo "== writing stamp into p2 =="
rm -f "$WORK/newid" "$WORK/newmf"
debugfs -w -R "rm /system/etc/ohos-image-id"  "$WORK/p2" >/dev/null 2>&1 || true
debugfs -w -R "rm /system/etc/ohos-image-id.manifest" "$WORK/p2" >/dev/null 2>&1 || true
debugfs -w -R "write $WORK/id  /system/etc/ohos-image-id"  "$WORK/p2" >/dev/null
debugfs -w -R "write $WORK/manifest /system/etc/ohos-image-id.manifest" "$WORK/p2" >/dev/null
e2fsck -f -y "$WORK/p2" >/dev/null 2>&1 || true

echo "== writing p2 back into $IMG =="
dd if="$WORK/p2" of="$IMG" bs=512 seek=$P2_START conv=notrunc,fsync status=none

echo "IMAGE_TAG=$TAG"
echo "P2_KEYFILES_SHA256=$P2KF"
echo "ESP_PART_SHA256=$ESP"
echo "new image sha256: $(sha256sum "$IMG" | cut -d' ' -f1)"
